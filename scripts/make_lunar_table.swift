#!/usr/bin/env swift
// Generates web/core/lunar-table.js: the Chinese calendar from 1900 to 2100,
// exported from Foundation's `Calendar(identifier: .chinese)` — the same
// source the native apps read.
//
// The web app cannot use the browser's own `Intl` Chinese calendar: engines
// ship different ICU builds and disagree. Chrome and Node (ICU 78) put
// 2027's Spring Festival on 7 February and 1987's leap month after the
// seventh month; Apple's ICU, and the published calendar, say 6 February and
// 闰六月. Exporting the table once pins every browser to the native apps.
//
// Usage: swift scripts/make_lunar_table.swift > web/core/lunar-table.js
import Foundation

let utc8 = TimeZone(secondsFromGMT: 8 * 3600)!
var chinese = Calendar(identifier: .chinese)
chinese.timeZone = utc8
var gregorian = Calendar(identifier: .gregorian)
gregorian.timeZone = utc8

struct MonthStart {
    let date: Date
    let month: Int
    let isLeap: Bool
}

// Every lunar month that starts between 1900 and early 2102, read at noon so
// no instant sits near a day boundary. ICU reports a "day 0" on two dates
// where a new moon grazes midnight (2057-09-28, 2097-08-07); keying on day 1
// counts each as the 30th of the month before.
var starts: [MonthStart] = []
var cursor = gregorian.date(from: DateComponents(year: 1900, month: 1, day: 1, hour: 12))!
let end = gregorian.date(from: DateComponents(year: 2102, month: 3, day: 1, hour: 12))!
while cursor < end {
    let c = chinese.dateComponents([.month, .day, .isLeapMonth], from: cursor)
    if c.day == 1 {
        starts.append(MonthStart(date: cursor, month: c.month!, isLeap: c.isLeapMonth!))
    }
    cursor = gregorian.date(byAdding: .day, value: 1, to: cursor)!
}

/// Days between two noons.
func days(_ a: Date, _ b: Date) -> Int {
    Int((b.timeIntervalSince(a) / 86400).rounded())
}

// One entry per lunar year, 1900...2100, packed as
//   offset << 17 | leapMonth << 13 | lengths
// where offset is the day of the Gregorian year (0 = 1 January) that 正月初一
// falls on, leapMonth is the month the leap month follows (0 for none), and
// bit i of lengths is set when the i-th month of the year, counting a leap
// month in sequence, has 30 days rather than 29.
var entries: [Int] = []
for year in 1900...2100 {
    guard let first = starts.firstIndex(where: {
        $0.month == 1 && !$0.isLeap && gregorian.component(.year, from: $0.date) == year
    }) else { fatalError("no 正月初一 in \(year)") }
    guard let next = starts[(first + 1)...].firstIndex(where: { $0.month == 1 && !$0.isLeap })
    else { fatalError("year \(year) does not end") }

    let months = Array(starts[first...next])
    var lengths = 0
    var leapMonth = 0
    for i in 0..<(months.count - 1) {
        let length = days(months[i].date, months[i + 1].date)
        precondition(length == 29 || length == 30, "\(year) month \(i) has \(length) days")
        if length == 30 { lengths |= 1 << i }
        if months[i].isLeap { leapMonth = months[i].month }
    }
    precondition(months.count - 1 == (leapMonth == 0 ? 12 : 13), "\(year) month count")

    let jan1 = gregorian.date(from: DateComponents(year: year, month: 1, day: 1, hour: 12))!
    let offset = days(jan1, months[0].date)
    precondition(offset >= 0 && offset < 64)
    entries.append(offset << 17 | leapMonth << 13 | lengths)
}

var lines: [String] = []
for chunk in stride(from: 0, to: entries.count, by: 8) {
    let row = entries[chunk..<min(chunk + 8, entries.count)]
        .map { "0x" + String($0, radix: 16, uppercase: false).leftPadded(to: 6) }
        .joined(separator: ", ")
    lines.append("  \(row),  // \(1900 + chunk)")
}

extension String {
    func leftPadded(to width: Int) -> String {
        String(repeating: "0", count: max(0, width - count)) + self
    }
}

print("""
// Generated by scripts/make_lunar_table.swift from Foundation's Chinese
// calendar. Do not edit by hand.
//
// One entry per lunar year from 1900 to 2100, packed as
//   offset << 17 | leapMonth << 13 | lengths
// offset: day of the Gregorian year (0 = 1 January) that 正月初一 falls on.
// leapMonth: the month the leap month follows, 0 for none.
// lengths: bit i set when the i-th month, counting a leap month in sequence,
// has 30 days rather than 29.

export const FIRST_YEAR = 1900;

export const YEARS = [
\(lines.joined(separator: "\n"))
];
""")
